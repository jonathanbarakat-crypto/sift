"""The mandatory banner every sim report carries.

SIMULATED — infrastructure validation, not user-behavior evidence.

Simulated users are synthetic load/attack patterns generated by this harness.
Their behavior validates that SIFT's infrastructure (queues, DB contention,
anti-abuse controls, append-only logs) behaves as designed under load and
attack. It says NOTHING about real users (spec §8) and must never be
presented as user-behavior evidence in any doc, report, or metric.
"""

SIM_HEADER = (
    "SIMULATED - infrastructure validation, not user-behavior evidence"
)

# One-line variant for machine-readable reports (JSON `sim` field).
SIM_HEADER_MACHINE = "simulated_infra_validation_not_user_evidence"


def header_lines(seed: int | None = None, sim_name: str | None = None) -> list[str]:
    """Report header lines: the banner first, then sim identity + seed."""
    lines = [SIM_HEADER]
    if sim_name:
        lines.append(f"sim: {sim_name}")
    if seed is not None:
        lines.append(f"seed: {seed} (deterministic: same seed -> same report)")
    lines.append(
        "scope: SIFT_ENV=test, ephemeral test DB only, synthetic instruments "
        "only — never production data, never real tickers"
    )
    return lines


__all__ = ["SIM_HEADER", "SIM_HEADER_MACHINE", "header_lines"]
