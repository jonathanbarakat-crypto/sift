"""Synthetic world + simulated users for the SIFT sim harness.

SIMULATED — infrastructure validation, not user-behavior evidence.

Everything here is SYNTHETIC:
- handles are `sim-user-XXXX`, never real accounts;
- instruments are synthetic symbols `SIM####` (never real tickers — v3 §12:
  no raw tickers/holdings anywhere near rendered or shared artifacts, and
  the sim never touches real data at all);
- prices are generated by seeded random walks / planted AR(1) spreads —
  synthetic instruments only, generated in-memory, never read from the
  warehouse (sims never touch production or vendor data);
- the whole world runs against an ephemeral test DB directory with
  `SIFT_ENV=test`.
"""

from __future__ import annotations

import os
from dataclasses import dataclass, field
from pathlib import Path

import numpy as np

from sift.cards.service import CardLayer
from sift.registry import Ledger

from .clock import DEFAULT_SEED, SimClock, SimRng

SIM_SCOPE_ID = "free_5y_top1k"  # registered scope label for sim trials (scope table entry; sim window is synthetic)
SIM_VINTAGE = "sim-vintage-synthetic"    # synthetic data vintage hash label
SIM_UNIVERSE_N = 12                      # synthetic instruments per sim world


def assert_test_env() -> None:
    """Hard constraint: sims only ever run with SIFT_ENV=test. Anything
    else fails closed — the harness must never run against production."""
    env = os.environ.get("SIFT_ENV", "dev")
    if env != "test":
        raise RuntimeError(
            f"sift/sim refuses to run with SIFT_ENV={env!r} — sims require "
            "SIFT_ENV=test (ephemeral test DB only, never production data)"
        )


def synth_symbol(i: int) -> str:
    """A synthetic instrument symbol. NOT a real ticker: the SIM prefix makes
    it unmistakably synthetic and it can never collide with a US ticker."""
    return f"SIM{i:04d}"


@dataclass
class SimUser:
    """One simulated user. All attributes synthetic."""
    handle: str
    device_id: str
    ip: str
    asn: str
    created_at: float
    completed_runs: int = 0
    tier: str = "bronze"  # vault tier of the cards it holds
    rng: SimRng = field(default_factory=lambda: SimRng(DEFAULT_SEED))


class SimWorld:
    """An ephemeral, fully synthetic SIFT environment for one sim run.

    Owns: the test DB dir (ledger + card layer), the fixed clock, the
    seeded RNG, the synthetic instrument universe + price panel, and the
    simulated user population. Everything is created fresh per sim (tmp
    dir), so sims never touch real data.
    """

    def __init__(self, db_dir: str | Path, *, seed: int = DEFAULT_SEED,
                 t0: float | None = None, n_users: int = 0,
                 universe_n: int = SIM_UNIVERSE_N):
        assert_test_env()
        self.db_dir = Path(db_dir)
        self.db_dir.mkdir(parents=True, exist_ok=True)
        self.seed = int(seed)
        self.rng = SimRng(self.seed)
        self.clock = SimClock(t0 if t0 is not None else 1_800_000_000.0)
        self.ledger = Ledger(self.db_dir / "ledger.db")
        self.layer = CardLayer(self.ledger, self.db_dir / "cards",
                               card_secret=b"sim-hmac-secret-test-only")
        self.universe = [synth_symbol(i) for i in range(universe_n)]
        self._prices = self._make_synth_panel(universe_n)
        self.users: list[SimUser] = []
        for i in range(n_users):
            self.users.append(self._make_user(i))

    # -- synthetic market ---------------------------------------------------

    def _make_synth_panel(self, n: int) -> np.ndarray:
        """A synthetic price panel (T x N) of pure random walks over
        synthetic instruments — generated in-memory from the sim seed.
        Never read from the warehouse; never contains real tickers."""
        T = 260  # one synthetic year of daily bars (small: sims are cheap)
        r = self.rng.normal(0.0, 0.01, (T, n))
        return 100.0 * np.cumprod(1.0 + r, axis=0)

    def synth_panel(self) -> np.ndarray:
        return self._prices

    # -- simulated users ------------------------------------------------------

    def _make_user(self, i: int) -> SimUser:
        rng = self.rng.spawn(1000 + i)
        return SimUser(
            handle=f"sim-user-{i:04d}",
            device_id=f"sim-dev-{self.seed}-{i:04d}",
            ip=f"10.{i // 250}.{(i // 25) % 250}.{i % 250 + 1}",
            asn=f"AS-SIM-{i % 7}",
            created_at=self.clock.now() - float(rng.integers(40 * 86400, 400 * 86400)),
            rng=rng,
        )

    def add_user(self, *, handle: str | None = None, device_id: str,
                 ip: str, asn: str, created_at: float,
                 rng: SimRng | None = None) -> SimUser:
        """Add a user with an explicit (attack-controlled) device/IP/ASN —
        used by the anti-abuse attack sims to build clusters."""
        u = SimUser(
            handle=handle or f"sim-user-x-{len(self.users):04d}",
            device_id=device_id, ip=ip, asn=asn,
            created_at=created_at, rng=rng or self.rng.spawn(9000 + len(self.users)),
        )
        self.users.append(u)
        return u

    # -- lifecycle -------------------------------------------------------------

    def close(self) -> None:
        try:
            self.layer.close()
        finally:
            self.ledger.close()

    def __enter__(self) -> "SimWorld":
        return self

    def __exit__(self, *exc) -> None:
        self.close()


