"""v4.1 card hit notifications (mechanics 7/8 — signal-delivery surface).

Per-card OPT-IN hit notifications for a user's own saved cards/connections
(v4.1 spec §2/§3 + v3 §7.2/§9.5):

- Notifications are SIGNAL-DELIVERY — monitoring the user's own saved
  connection — NOT bets. SIFT never executes (v3 §12.1 unchanged); the
  payload carries only the survival-fact signal event, never a directional
  call, never a ticker+direction pair, never P&L (v3 §12 hard rules).
- Opt-in PER CARD: nothing is sent unless the owner explicitly enabled
  notifications for that card. On the FREE tier the default delivery mode
  is the rate-capped DIGEST; live (per-hit) delivery is a PAID-tier
  entitlement (`entitlement="live"`). A free-tier user asking for live on
  a card gets the digest mode instead (never an error, never spam).
- Rate caps (no push spam, no loss-aversion triggers, no countdown timers):
  live hits are capped per card per day; digest batches at most one email
  per day; lifecycle emails (mint, decay/downgrade, digest summary) stay
  capped at 1 per week per card (v3 §7.2).
- Ghost cards (pull/14) keep FULL personal utility including notifications:
  the per-card prefs + queue work identically for kind='ghost'.
- Queue: an append-only notification log (rows are inserted, never
  updated/deleted) + a pending outbox queue. `deliver_due` marks queued
  rows delivered exactly once (idempotent).

Flag: every path is behind `cards_v4_1`; flag off -> NotifyError(flag_off)
for mutations, reads stay available (kill-switch never hides data).
Kill-switch env: SIFT_CARDS_V4_1=0 (sift/flags.py).

Copy discipline (legal posture §6): no "value appreciates" language
anywhere — rarity/tier language only. Notification copy is generated by
`copy_for_event`, which is the ONLY place user-facing text is built and is
covered by a test that greps it for banned phrases.

Read-back discipline (hard rule): every write is followed by a GET from
the DB before the result is returned.
"""

from __future__ import annotations

import json
import re
import sqlite3
import time
from dataclasses import dataclass
from pathlib import Path

from sift import db, flags
from sift.cards import CardRegistry

# Delivery modes (v3 §7.2 monitoring row: free = daily digest, paid = live).
MODE_DIGEST = "digest"
MODE_LIVE = "live"
DELIVERY_MODES = (MODE_DIGEST, MODE_LIVE)

# Paid entitlement that unlocks live per-hit delivery. Free tier -> digest.
LIVE_ENTITLEMENT = "live"

# Rate caps (no push spam):
#   live: at most LIVE_CAP_PER_CARD_PER_DAY hits delivered per card per day
#   digest: at most one digest batch per card per day (batches the hits)
#   lifecycle (mint/decay/summary): at most 1 per card per week (v3 §7.2)
LIVE_CAP_PER_CARD_PER_DAY = 5
DIGEST_CAP_PER_CARD_PER_DAY = 1
LIFECYCLE_CAP_PER_CARD_PER_WEEK = 1
DAY = 86400.0
WEEK = 7 * DAY

# Event kinds. `hit` is a signal event on a monitored connection (signal
# delivery only); `digest` is the batched digest summary of hit rows;
# `lifecycle` covers mint/decay emails.
EVENT_HIT = "hit"
EVENT_DIGEST = "digest"
EVENT_LIFECYCLE = "lifecycle"
EVENT_KINDS = (EVENT_HIT, EVENT_DIGEST, EVENT_LIFECYCLE)

# Queue states. Rows move queued -> delivered exactly once (append-only
# log: the state transition is an UPDATE of the state column only; the
# row + payload are never rewritten or deleted).
STATE_QUEUED = "queued"
STATE_DELIVERED = "delivered"

# Banned copy (legal posture §6 + dark-pattern rules + v3 §12 red lines):
# no appreciation language, no urgency/loss-aversion, no countdowns, no
# "act now", no P&L or returns, no profit-expectation/"value" language —
# these are SUBSTRING bans and cover EVERY string built in `copy_for_event`
# (including upgrade copy), the rich hit gloss (magnitude only), and the
# decay public explanations.
BANNED_PHRASES = (
    "appreciat", "moon", "guaranteed", "risk-free", "act now", "don't miss",
    "last chance", "countdown", "expires in", "going up", "pump", "to the moon",
    # profit-expectation / value language (v3 §12 + v4.1 §6, upgrade copy too)
    "pnl", "p&l", "value", "valuable", "profit", "gained", "worth", "price",
    "return", "yield", "invest",
)

# Directional / trade words are banned as WHOLE WORDS only (word-boundary
# match) so legitimate prose like "no longer supports" is not caught —
# "long" as a substring would false-positive on "longer".
BANNED_WORDS = ("buy", "sell", "long", "short")
_BANNED_WORD_RE = re.compile(
    r"\b(?:" + "|".join(BANNED_WORDS) + r")\b", re.IGNORECASE
)


def contains_banned(text: str) -> str | None:
    """Return the first banned phrase/word found in `text` (lowercased
    substring scan over BANNED_PHRASES, word-boundary scan over
    BANNED_WORDS), or None when the text is clean. This is the single
    fail-closed check used by `copy_for_event` AND by the decay public
    explanations (sift/cards/decay.py) — the banned-phrase grep test covers
    every user-facing string through this helper."""
    low = text.lower()
    for phrase in BANNED_PHRASES:
        if phrase in low:
            return phrase
    m = _BANNED_WORD_RE.search(low)
    if m:
        return m.group(0)
    return None

_SCHEMA_SQL = """
CREATE TABLE IF NOT EXISTS notify_pref (
    card_id     TEXT NOT NULL,
    owner       TEXT NOT NULL,
    enabled     INTEGER NOT NULL DEFAULT 0,     -- opt-in per card; default OFF
    mode        TEXT NOT NULL DEFAULT 'digest',  -- digest|live (live needs paid entitlement)
    updated_at  REAL NOT NULL,
    PRIMARY KEY (card_id, owner)
);
CREATE TABLE IF NOT EXISTS notify_log (
    notif_id    INTEGER PRIMARY KEY AUTOINCREMENT,  -- append-only log
    card_id     TEXT NOT NULL,
    owner       TEXT NOT NULL,
    event_kind  TEXT NOT NULL,                   -- hit|lifecycle
    mode        TEXT NOT NULL,                   -- delivery mode used
    payload_json TEXT NOT NULL,                  -- signal event; survival facts only
    state       TEXT NOT NULL DEFAULT 'queued',  -- queued|delivered
    created_at  REAL NOT NULL,
    delivered_at REAL
);
CREATE INDEX IF NOT EXISTS idx_notify_log_owner ON notify_log(owner, created_at);
CREATE INDEX IF NOT EXISTS idx_notify_log_state ON notify_log(state);
"""


class NotifyError(Exception):
    """Notification misuse: unknown card, flag off, rate cap hit, ..."""


@dataclass(frozen=True)
class NotifyPref:
    card_id: str
    owner: str
    enabled: bool
    mode: str
    updated_at: float


@dataclass(frozen=True)
class Notification:
    notif_id: int
    card_id: str
    owner: str
    event_kind: str
    mode: str
    payload: dict
    state: str
    created_at: float
    delivered_at: float | None


def copy_for_event(event: str, card, detail: dict | None = None) -> str:
    """The ONLY user-facing notification copy builder. Rarity/survival
    language only — never appreciation, urgency, or directional language.
    Raises NotifyError if a banned phrase would slip in (fail closed)."""
    detail = detail or {}
    if event == "hit":
        stat = detail.get("statistic")
        thr = detail.get("threshold")
        mag = ""
        if stat is not None and thr is not None:
            mag = (f" The monitored spread is at magnitude {stat} against its "
                   f"pre-registered entry band of {thr} (magnitude only — the "
                   f"event carries no sign and no leg).")
        text = (
            f"Signal event on your saved connection (card {card.card_id}, "
            f"{card.family} in {card.scope_id}, tier {card.tier}): the "
            f"monitored relationship is currently stretched beyond its usual "
            f"range.{mag} This is an observation about the signal, not a "
            f"recommendation — signal delivery only; SIFT does not trade."
        )
    elif event == "minted":
        text = (
            f"A new card was minted for you (card {card.card_id}, {card.family} "
            f"in {card.scope_id}, rarity tier {card.tier}). Survival facts only — "
            f"not a recommendation; SIFT does not trade."
        )
    elif event == "decay":
        old = detail.get("from_tier", "?")
        new = detail.get("to_tier", card.tier)
        text = (
            f"Registry re-evaluation downgraded card {card.card_id} from {old} "
            f"to {new} (rarity tier, amber). Tiers move down on re-evaluation "
            f"and can rise only when the pre-registered live-window rules are "
            f"met — never by payment or chance. Survival facts only; not a "
            f"recommendation."
        )
    elif event == "upgrade":
        old = detail.get("from_tier", "?")
        new = detail.get("to_tier", card.tier)
        text = (
            f"Card {card.card_id} was re-validated on live data — rarity tier "
            f"raised from {old} to {new} (green). The upgrade fired only "
            f"because the pre-registered live-window rules were met on two "
            f"consecutive fully out-of-sample annual windows; never by "
            f"payment or chance. Survival facts only; not a recommendation."
        )
    elif event == "digest":
        n = detail.get("hit_count", 0)
        text = (
            f"Daily digest: {n} signal event(s) on your monitored card(s) "
            f"(incl. card {card.card_id}). Signal delivery only — SIFT does "
            f"not trade and this is not a recommendation."
        )
    else:
        raise NotifyError(f"unknown notification event {event!r}")
    banned = contains_banned(text)
    if banned is not None:
        raise NotifyError(f"copy contains banned phrase {banned!r} — refused")
    return text


class Notifier:
    """Per-card opt-in notification prefs + append-only queue.
    Server-side only."""

    def __init__(
        self,
        cards: CardRegistry,
        db_path: str | Path | None = None,
        *,
        con: sqlite3.Connection | None = None,
    ):
        self.cards = cards
        if con is not None or db_path is None:
            shared = con if con is not None else cards.con
            self.con = shared
            self._owns_con = False
            self.db_path = (
                Path(db_path) if db_path is not None else (db.db_path_of(shared) or cards.db_path)
            )
            self.con.row_factory = sqlite3.Row
            self.con.execute("PRAGMA foreign_keys = ON")
        else:
            self.db_path = Path(db_path)
            self.con = db.connect(self.db_path)
            self._owns_con = True
        self.con.executescript(_SCHEMA_SQL)
        db.maybe_commit(self.con)

    def __enter__(self) -> "Notifier":
        return self

    def __exit__(self, *exc) -> None:
        self.close()

    def close(self) -> None:
        if self._owns_con:
            self.con.close()

    # -- flag guard -------------------------------------------------------------

    def _require_flag(self, handle: str) -> None:
        if not flags.cards_v4_1_enabled(handle):
            raise NotifyError("flag_off: cards_v4_1 is disabled for this account")

    # -- entitlement / mode -------------------------------------------------------

    def effective_mode(self, handle: str, requested_mode: str,
                       entitlement: str | None = None) -> str:
        """Delivery mode resolution (v3 §7.2): free tier defaults to digest;
        live per-hit delivery requires the paid `live` entitlement. A free
        user requesting live gets digest (never an error, never spam)."""
        if requested_mode not in DELIVERY_MODES:
            raise NotifyError(f"unknown delivery mode {requested_mode!r}")
        if requested_mode == MODE_LIVE and entitlement != LIVE_ENTITLEMENT:
            return MODE_DIGEST
        return requested_mode

    # -- per-card prefs ------------------------------------------------------------

    def set_pref(self, card_id: str, handle: str, enabled: bool,
                 mode: str = MODE_DIGEST, entitlement: str | None = None,
                 now: float | None = None) -> NotifyPref:
        """Opt-in per card (default OFF). `mode` is resolved through
        effective_mode: live only with the paid entitlement. Read-back."""
        self._require_flag(handle)
        self.cards.assert_owned(card_id, handle)   # non-transferable
        mode = self.effective_mode(handle, mode, entitlement)
        now = time.time() if now is None else now
        self.con.execute(
            "INSERT INTO notify_pref (card_id, owner, enabled, mode, updated_at)"
            " VALUES (?,?,?,?,?)"
            " ON CONFLICT(card_id, owner) DO UPDATE SET enabled=excluded.enabled,"
            " mode=excluded.mode, updated_at=excluded.updated_at",
            (card_id, handle, 1 if enabled else 0, mode, now),
        )
        db.maybe_commit(self.con)
        return self.get_pref(card_id, handle)             # read-back

    def get_pref(self, card_id: str, handle: str) -> NotifyPref:
        row = self.con.execute(
            "SELECT * FROM notify_pref WHERE card_id=? AND owner=?", (card_id, handle)
        ).fetchone()
        if row is None:
            # default: opt-in OFF, digest mode (free default)
            return NotifyPref(card_id, handle, enabled=False, mode=MODE_DIGEST,
                              updated_at=0.0)
        return self._to_pref(row)

    def prefs_for_owner(self, handle: str) -> list[NotifyPref]:
        rows = self.con.execute(
            "SELECT * FROM notify_pref WHERE owner=? ORDER BY updated_at", (handle,)
        ).fetchall()
        return [self._to_pref(r) for r in rows]

    def _to_pref(self, row: sqlite3.Row) -> NotifyPref:
        return NotifyPref(row["card_id"], row["owner"], bool(row["enabled"]),
                          row["mode"], row["updated_at"])

    # -- rate caps ----------------------------------------------------------------

    def _count_since(self, card_id: str, event_kind: str, mode: str | None,
                     since: float) -> int:
        """Rows of this kind (and mode, unless None) created since `since`,
        any state — the cap counts queued AND delivered rows so a cap can
        never be exceeded by re-queueing."""
        if mode is None:
            row = self.con.execute(
                "SELECT COUNT(*) c FROM notify_log WHERE card_id=? AND event_kind=?"
                " AND created_at>=?",
                (card_id, event_kind, since),
            ).fetchone()
        else:
            row = self.con.execute(
                "SELECT COUNT(*) c FROM notify_log WHERE card_id=? AND event_kind=?"
                " AND mode=? AND created_at>=?",
                (card_id, event_kind, mode, since),
            ).fetchone()
        return row["c"]

    def _cap_for(self, event_kind: str, mode: str) -> tuple[float, int]:
        """(window_seconds, max_count) for the rate cap of this event/mode.

        - lifecycle (mint/decay emails): 1 per card per WEEK (v3 §7.2),
          counted across modes.
        - digest summary: 1 per card per day (the free-tier digest).
        - live hit: LIVE_CAP per card per day.
        - hit in digest mode: NOT capped at enqueue — hits queue up and are
          delivered by the (capped) daily digest batch.
        """
        if event_kind == EVENT_LIFECYCLE:
            return (WEEK, LIFECYCLE_CAP_PER_CARD_PER_WEEK)   # v3 §7.2: 1/week
        if event_kind == EVENT_DIGEST:
            return (DAY, DIGEST_CAP_PER_CARD_PER_DAY)
        if mode == MODE_LIVE:
            return (DAY, LIVE_CAP_PER_CARD_PER_DAY)
        return (DAY, DIGEST_CAP_PER_CARD_PER_DAY)

    def within_cap(self, card_id: str, event_kind: str, mode: str,
                   now: float | None = None) -> bool:
        """True if one more notification of this kind/mode is under the cap."""
        now = time.time() if now is None else now
        window, cap = self._cap_for(event_kind, mode)
        count_mode = None if event_kind == EVENT_LIFECYCLE else mode
        return self._count_since(card_id, event_kind, count_mode, now - window) < cap

    # -- enqueue (the write path) ---------------------------------------------------

    def notify(self, card_id: str, handle: str, event: str,
               payload: dict | None = None, *,
               entitlement: str | None = None,
               now: float | None = None) -> Notification | None:
        """Enqueue a notification for the owner's own card.

        - Opt-in: if the per-card pref is disabled, nothing is enqueued
          (returns None) — notifications are strictly opt-in per card.
        - Rate cap: if the cap for (kind, mode) is reached, returns None
          (capped, never spammed).
        - Mode: pref mode resolved against entitlement (free -> digest).
        - Ghost cards: full utility — identical path (kind is not special-
          cased anywhere here).
        - Payload discipline: hits carry signal-event survival facts only
          (caller-supplied payload is checked for banned copy at delivery).

        Read-back: the returned Notification is re-read from the DB.
        """
        self._require_flag(handle)
        card = self.cards.assert_owned(card_id, handle)   # non-transferable
        pref = self.get_pref(card_id, handle)
        if not pref.enabled:
            return None                                   # opt-in: default off
        mode = self.effective_mode(handle, pref.mode, entitlement)
        event_kind = EVENT_HIT if event == "hit" else EVENT_LIFECYCLE
        now = time.time() if now is None else now
        # Rate cap: live hits and lifecycle emails are capped at enqueue;
        # digest-mode hits queue uncapped and are delivered by the capped
        # daily digest batch (no push spam: digest users get <=1 email/day).
        if event_kind != EVENT_HIT or mode == MODE_LIVE:
            if not self.within_cap(card_id, event_kind, mode, now=now):
                return None                               # rate-capped
        payload = dict(payload or {})
        payload.setdefault("event", event)
        payload["card_id"] = card_id
        payload["kind"] = card.kind                       # regular|ghost — full utility
        payload["tier"] = card.tier
        payload["copy"] = copy_for_event(event, card, payload)
        self.con.execute(
            "INSERT INTO notify_log (card_id, owner, event_kind, mode,"
            " payload_json, state, created_at) VALUES (?,?,?,?,?,'queued',?)",
            (card_id, handle, event_kind, mode, json.dumps(payload, default=str), now),
        )
        db.maybe_commit(self.con)
        row = self.con.execute(
            "SELECT * FROM notify_log WHERE notif_id=last_insert_rowid()"
        ).fetchone()
        return self._to_notif(row)                        # read-back

    # -- digest batching --------------------------------------------------------------

    def digest_batch(self, handle: str, *, entitlement: str | None = None,
                     now: float | None = None) -> list[Notification]:
        """Batch all QUEUED hit notifications of the owner's digest-mode cards
        into one digest notification per card (rate-capped: at most one digest
        per card per day). The individual hit rows stay in the append-only log
        marked delivered; the digest row is appended. Returns the digest rows
        (read-back)."""
        self._require_flag(handle)
        now = time.time() if now is None else now
        out: list[Notification] = []
        # digest-mode, enabled prefs of this owner
        prefs = [p for p in self.prefs_for_owner(handle)
                 if p.enabled and self.effective_mode(handle, p.mode, entitlement) == MODE_DIGEST]
        for pref in prefs:
            hits = self.con.execute(
                "SELECT * FROM notify_log WHERE card_id=? AND owner=? AND event_kind=?"
                " AND state=? ORDER BY notif_id",
                (pref.card_id, handle, EVENT_HIT, STATE_QUEUED),
            ).fetchall()
            if not hits:
                continue
            # digest cap: at most 1 digest summary per card per day
            if not self.within_cap(pref.card_id, EVENT_DIGEST, MODE_DIGEST, now=now):
                continue
            card = self.cards.get_card(pref.card_id)
            payload = {
                "event": "digest",
                "card_id": pref.card_id,
                "kind": card.kind,
                "tier": card.tier,
                "hit_count": len(hits),
                "hit_ids": [h["notif_id"] for h in hits],
            }
            payload["copy"] = copy_for_event("digest", card, payload)
            self.con.execute(
                "INSERT INTO notify_log (card_id, owner, event_kind, mode,"
                " payload_json, state, created_at) VALUES (?,?,?,?,?,'queued',?)",
                (pref.card_id, handle, EVENT_DIGEST, MODE_DIGEST,
                 json.dumps(payload, default=str), now),
            )
            # mark the batched hits delivered (state transition only; rows kept)
            for h in hits:
                self.con.execute(
                    "UPDATE notify_log SET state=?, delivered_at=? WHERE notif_id=?",
                    (STATE_DELIVERED, now, h["notif_id"]),
                )
            out.append(self.get_notif(int(self.con.execute(
                "SELECT last_insert_rowid() x").fetchone()["x"])))
        db.maybe_commit(self.con)
        return out

    # -- delivery ----------------------------------------------------------------------

    def deliver_due(self, handle: str | None = None,
                    now: float | None = None) -> list[Notification]:
        """Mark all queued rows (optionally one owner's) delivered, exactly
        once. Returns the delivered rows (read-back). Live-mode rows are
        delivered immediately by this pass; digest-mode hit rows are
        delivered by digest_batch (they are batched first)."""
        now = time.time() if now is None else now
        # fail closed on the flag for both the per-user and the global path
        self._require_flag(handle if handle is not None else "")
        if handle is None:
            rows = self.con.execute(
                "SELECT * FROM notify_log WHERE state=? ORDER BY notif_id",
                (STATE_QUEUED,),
            ).fetchall()
        else:
            rows = self.con.execute(
                "SELECT * FROM notify_log WHERE state=? AND owner=? ORDER BY notif_id",
                (STATE_QUEUED, handle),
            ).fetchall()
        delivered: list[Notification] = []
        for r in rows:
            self.con.execute(
                "UPDATE notify_log SET state=?, delivered_at=? WHERE notif_id=?"
                " AND state=?",
                (STATE_DELIVERED, now, r["notif_id"], STATE_QUEUED),
            )
            delivered.append(self.get_notif(r["notif_id"]))   # read-back
        db.maybe_commit(self.con)
        return delivered

    # -- reads --------------------------------------------------------------------------

    def get_notif(self, notif_id: int) -> Notification:
        row = self.con.execute(
            "SELECT * FROM notify_log WHERE notif_id=?", (notif_id,)
        ).fetchone()
        if row is None:
            raise NotifyError(f"unknown notif_id {notif_id!r}")
        return self._to_notif(row)

    def log_for_card(self, card_id: str) -> list[Notification]:
        """Append-only log for one card, oldest first (never hides rows)."""
        rows = self.con.execute(
            "SELECT * FROM notify_log WHERE card_id=? ORDER BY notif_id", (card_id,)
        ).fetchall()
        return [self._to_notif(r) for r in rows]

    def log_for_owner(self, handle: str) -> list[Notification]:
        rows = self.con.execute(
            "SELECT * FROM notify_log WHERE owner=? ORDER BY notif_id", (handle,)
        ).fetchall()
        return [self._to_notif(r) for r in rows]

    def pending(self, handle: str) -> list[Notification]:
        rows = self.con.execute(
            "SELECT * FROM notify_log WHERE owner=? AND state=? ORDER BY notif_id",
            (handle, STATE_QUEUED),
        ).fetchall()
        return [self._to_notif(r) for r in rows]

    def _to_notif(self, row: sqlite3.Row) -> Notification:
        try:
            payload = json.loads(row["payload_json"])
        except (ValueError, TypeError):
            payload = {"_raw": row["payload_json"]}
        return Notification(
            notif_id=row["notif_id"], card_id=row["card_id"], owner=row["owner"],
            event_kind=row["event_kind"], mode=row["mode"], payload=payload,
            state=row["state"], created_at=row["created_at"],
            delivered_at=row["delivered_at"],
        )


